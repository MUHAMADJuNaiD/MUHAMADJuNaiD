import os, sys, json, math, subprocess, numpy as np
from scipy.io import wavfile
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import make_audio as A
from make_audio import SR, t_, lp, hp, bp, reverb, NOTE, norm

MAJ, MIN = [0, 2, 4, 5, 7, 9, 11], [0, 2, 3, 5, 7, 8, 10]

def chord(root, mode, deg, octave=0):
    sc = MAJ if mode == 'maj' else MIN
    return [root + 12 * octave + sc[(deg + k) % 7] + 12 * ((deg + k) // 7) for k in (0, 2, 4)]

def place(buf, x, at):
    s = int(at * SR)
    if s >= len(buf): return
    e = min(len(buf), s + len(x)); buf[s:e] += x[:e - s]

def dec(n, d): return np.exp(-np.linspace(0, d, n))
# ---------- instruments
def kick(v=1., f0=140, f1=45, d=9, L=.4):
    t = t_(L); f = (f0 - f1) * np.exp(-t * 30) + f1
    return np.tanh(1.4 * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * d)) * v
def snare(v=.5, tone=190):
    t = t_(.25); n = bp(rng.standard_normal(len(t)), 1500, 7000) * np.exp(-t * 20) + np.sin(2 * np.pi * tone * t) * np.exp(-t * 30) * .5
    return reverb(n, .6, .2) * v
def clap(v=.5): return A.clap(v)
def snap(v=.4):
    t = t_(.12); return (hp(rng.standard_normal(len(t)), 2500) * np.exp(-t * 60) + np.sin(2 * np.pi * 1800 * t) * np.exp(-t * 90) * .3) * v
def hat(v=.2, open_=False): return A.hat(v, open_)
def shaker(v=.12):
    t = t_(.09); return hp(rng.standard_normal(len(t)), 5000) * np.sin(np.pi * np.linspace(0, 1, len(t))) ** 2 * v
def rim(v=.3):
    t = t_(.07); return (np.sin(2 * np.pi * 1700 * t) + bp(rng.standard_normal(len(t)), 1500, 5000) * .6) * np.exp(-t * 80) * v
def conga(f, v=.4):
    t = t_(.3); ff = f * (1 + .3 * np.exp(-t * 40)); return np.sin(2 * np.pi * np.cumsum(ff) / SR) * np.exp(-t * 14) * v
def tom(f=90, v=.7):
    t = t_(.8); ff = f * (1 + .6 * np.exp(-t * 18)); return reverb(np.tanh(2 * np.sin(2 * np.pi * np.cumsum(ff) / SR) * np.exp(-t * 6)), 1.4, .3) * v
def saw(f, d, cut=2500, v=.2, det=1.006):
    t = t_(d); x = (2 * ((f * t) % 1) - 1) + (2 * ((f * det * t) % 1) - 1); return lp(x, cut) * v
def sq(f, d, cut=2000, v=.2):
    t = t_(d); return lp(np.sign(np.sin(2 * np.pi * f * t)), cut) * v
def sine(f, d, v=.3): t = t_(d); return np.sin(2 * np.pi * f * t) * v
def sub808(f, d, v=.6, slide=None):
    t = t_(d); ff = np.full(len(t), f) if slide is None else f * (slide / f) ** np.clip(t / (d * .6), 0, 1)
    return np.tanh(1.8 * np.sin(2 * np.pi * np.cumsum(ff) / SR)) * np.exp(-t * 1.2) * v
def pluck(f, d, v=.2, bright=1.):
    t = t_(d); x = sum(np.sin(2 * np.pi * f * h * t) * np.exp(-t * (4 + h * 3 / bright)) / h for h in range(1, 7)); return x * v
def marimba(f, d, v=.25):
    t = t_(d); return (np.sin(2 * np.pi * f * t) + .25 * np.sin(2 * np.pi * f * 4 * t) * np.exp(-t * 30)) * np.exp(-t * 7) * v
def epiano(f, d, v=.2):
    t = t_(d); return (np.sin(2 * np.pi * f * t) + .3 * np.sin(2 * np.pi * f * 2 * t) * np.exp(-t * 3)) * np.exp(-t * 1.8) * (1 + .15 * np.sin(2 * np.pi * 5 * t)) * v
def bell(f, d, v=.18):
    t = t_(d); return (np.sin(2 * np.pi * f * t) + .5 * np.sin(2 * np.pi * f * 2.76 * t) * np.exp(-t * 3) + .25 * np.sin(2 * np.pi * f * 5.4 * t) * np.exp(-t * 6)) * np.exp(-t * 2.2) * v
def pad(notes, d, v=.07, cut=1500, att=.25):
    x = sum(saw(NOTE(n), d, cut, 1, 1.004) + saw(NOTE(n) * .998, d, cut, 1, 1.009) for n in notes)
    n = len(x); a = max(1, int(att * SR)); e = np.ones(n); e[:a] = np.linspace(0, 1, a); e[-int(.3 * SR):] *= np.linspace(1, 0, int(.3 * SR)); return x * e * v
def strings(notes, d, v=.06): return pad(notes, d, v, 2400, .6)

# ---------- styles
STYLE = {
 'house':     dict(bpm=(122, 124, 120), mode=('min', 'maj', 'min'), fits=['tops-winterwear', 'bottoms', 'sunglasses'], mood='upbeat', energy='high'),
 'disco':     dict(bpm=(118, 116, 120), mode=('maj', 'min', 'maj'), fits=['bottoms', 'blouses-shirts', 'coords-dresses'], mood='fun', energy='high'),
 'garage':    dict(bpm=(128, 130, 126), mode=('min', 'min', 'maj'), fits=['tops-winterwear', 'bottoms'], mood='cool', energy='high'),
 'lofi':      dict(bpm=(86, 90, 84), mode=('maj', 'maj', 'min'), fits=['blouses-shirts', 'tops-winterwear', 'coords-dresses'], mood='chill', energy='low'),
 'trap':      dict(bpm=(140, 144, 138), mode=('min', 'min', 'min'), fits=['handbags', 'sunglasses', 'tops-winterwear'], mood='bold', energy='high'),
 'synthwave': dict(bpm=(104, 108, 100), mode=('min', 'maj', 'min'), fits=['sunglasses', 'tops-winterwear', 'bottoms'], mood='retro', energy='mid'),
 'afro':      dict(bpm=(108, 106, 110), mode=('maj', 'min', 'maj'), fits=['bottoms', 'eastern', 'coords-dresses'], mood='warm', energy='mid'),
 'luxe':      dict(bpm=(92, 96, 90), mode=('min', 'min', 'maj'), fits=['handbags', 'flats-jewellery', 'coords-dresses', 'eastern'], mood='luxury', energy='mid'),
 'soft':      dict(bpm=(112, 116, 110), mode=('maj', 'maj', 'min'), fits=['blouses-shirts', 'coords-dresses', 'flats-jewellery'], mood='elegant', energy='low'),
 'cinematic': dict(bpm=(90, 88, 94), mode=('min', 'maj', 'min'), fits=['eastern', 'handbags', 'flats-jewellery', 'coords-dresses'], mood='epic', energy='mid'),
}
PROG = {'maj': [[0, 4, 5, 3], [5, 3, 0, 4], [0, 5, 3, 4], [1, 4, 0, 5]], 'min': [[0, 5, 2, 6], [0, 3, 5, 4], [0, 6, 5, 6], [0, 4, 3, 5]]}
KEYS = [57, 60, 55, 62, 53, 58, 56, 59, 54, 61]

def build(style, v, seed):
    global rng
    rng = np.random.default_rng(seed); A.rng = rng
    S = STYLE[style]; bpm = S['bpm'][v]; mode = S['mode'][v]; root = KEYS[(seed + v * 3) % len(KEYS)]
    prog = PROG[mode][(seed + v) % 4]; beat = 60 / bpm; bar = 4 * beat; s16 = beat / 4
    bars = math.ceil(17.5 / bar); L = int(SR * (bars * bar + 1.2))
    dr, bs, ky, ld, pump = (np.zeros(L) for _ in range(5))
    swing = .33 if style in ('lofi', 'garage') else 0
    def at(b, step): return b * bar + step * s16 + (swing * s16 if step % 2 else 0)
    motif = [int(x) for x in rng.integers(0, 3, 8)]; mpat = [int(x) for x in rng.choice([0, 1], 8, p=[.4, .6])]
    for b in range(bars):
        ch = chord(root, mode, prog[b % 4]); bassn = ch[0] - 24
        intro = style == 'cinematic' and b < 2
        # ---- drums
        if style in ('house', 'disco'):
            for q in range(4): A_ = place(dr, kick(1), at(b, q * 4))
            for s in (4, 12): place(dr, clap(.5) if style == 'house' else snare(.45), at(b, s))
            for s in (2, 6, 10, 14): place(dr, hat(.22, True), at(b, s))
            if style == 'house': [place(dr, hat(.1), at(b, s)) for s in (1, 3, 5, 7, 9, 11, 13, 15)]
        elif style == 'garage':
            for s in (0, 7, 10): place(dr, kick(.95), at(b, s))
            for s in (4, 12): place(dr, snare(.5), at(b, s))
            for s in range(0, 16, 2): place(dr, hat(.14), at(b, s + 1))
        elif style == 'lofi':
            for s in (0, 7, 10): place(dr, kick(.75, 110, 50, 12), at(b, s))
            for s in (4, 12): place(dr, snare(.32, 170), at(b, s))
            for s in range(0, 16, 2): place(dr, hat(.08), at(b, s))
        elif style == 'trap':
            for s in (0, 10) + ((6,) if b % 2 else ()): place(dr, kick(.9, 160, 50, 7), at(b, s))
            place(dr, clap(.55), at(b, 8))
            for s in range(16): place(dr, hat(.1), at(b, s))
            if b % 2: [place(dr, hat(.07), b * bar + 14 * s16 + k * s16 / 3) for k in range(6)]
        elif style == 'synthwave':
            for s in (0, 8): place(dr, kick(1, 120, 48, 8), at(b, s))
            for s in (4, 12): place(dr, reverb(snare(.5, 180), 1.6, .4), at(b, s))
            for s in range(0, 16, 2): place(dr, hat(.1), at(b, s))
        elif style == 'afro':
            for s in (0, 6, 10): place(dr, kick(.85, 120, 50, 10), at(b, s))
            for s in range(16): place(dr, shaker(.1 if s % 2 else .14), at(b, s))
            for s in (3, 6, 10, 13): place(dr, rim(.25), at(b, s))
            for s, f in ((2, 220), (7, 330), (11, 260), (14, 330)): place(dr, conga(f, .3), at(b, s))
        elif style == 'luxe':
            for s in (0, 10): place(dr, kick(.85, 120, 42, 6), at(b, s))
            place(dr, snap(.4), at(b, 8))
            for s in (2, 6, 10, 14): place(dr, hat(.07), at(b, s))
        elif style == 'soft':
            for s in (0, 8): place(dr, kick(.6, 110, 55, 12), at(b, s))
            place(dr, snap(.3), at(b, 8))
            for s in range(0, 16, 2): place(dr, shaker(.09), at(b, s))
        elif style == 'cinematic' and not intro:
            for s in (0, 6, 8, 12): place(dr, tom(80 if s % 8 == 0 else 110, .55), at(b, s))
            if b == 2: place(dr, tom(55, 1.0), at(b, 0))
        # ---- bass
        if style in ('house', 'garage'):
            for s in (2, 6, 10, 14): place(bs, lp(saw(NOTE(bassn), s16 * 1.6, 500, .5), 320), at(b, s))
        elif style == 'disco':
            for s in range(0, 16, 2): place(bs, lp(saw(NOTE(bassn + (12 if (s // 2) % 2 else 0)), s16 * 1.7, 700, .4), 500), at(b, s))
        elif style == 'trap':
            place(bs, sub808(NOTE(bassn), bar * .9, .55, NOTE(bassn - 2) if b % 4 == 3 else None), at(b, 0))
        elif style == 'synthwave':
            for s in range(0, 16, 2): place(bs, sq(NOTE(bassn), s16 * 1.8, 600, .28), at(b, s))
        elif style == 'cinematic':
            place(bs, sine(NOTE(bassn - 12 + 12), bar, .4) * dec(int(bar * SR), 2), at(b, 0))
        else:
            place(bs, sine(NOTE(bassn), bar * .95, .45) * dec(int(bar * .95 * SR), 2.5), at(b, 0))
        # ---- harmony
        if style == 'house':
            for s in (0, 6, 10): place(ky, sum(saw(NOTE(n), s16 * 1.8, 3000, .08) for n in ch) * dec(int(s16 * 1.8 * SR), 4), at(b, s))
        elif style == 'disco':
            place(ky, strings(ch, bar, .05), at(b, 0))
            for s in (4, 12): place(ky, sum(pluck(NOTE(n), s16 * 2, .12) for n in ch), at(b, s))
        elif style == 'garage':
            for s in (3, 11): place(ky, sum(epiano(NOTE(n), s16 * 3, .12) for n in ch), at(b, s))
        elif style == 'lofi':
            place(ky, sum(epiano(NOTE(n + 12), bar, .13) for n in ch), at(b, 0))
        elif style == 'trap':
            place(ky, pad(ch, bar, .035, 1200, .3), at(b, 0))
        elif style == 'synthwave':
            place(ky, pad(ch, bar, .05, 1800, .4), at(b, 0))
        elif style == 'afro':
            place(ky, pad(ch, bar, .03, 1300, .4), at(b, 0))
        elif style in ('luxe', 'cinematic'):
            place(ky, strings(ch, bar, .06 if style == 'cinematic' else .05), at(b, 0))
        elif style == 'soft':
            place(ky, pad(ch, bar, .025, 1100, .5), at(b, 0))
        # ---- lead / motif
        tones = ch + [ch[0] + 12]
        if style in ('synthwave', 'soft'):
            for s in range(0, 16, 2 if style == 'soft' else 1):
                n = tones[(s // (2 if style == 'soft' else 1)) % 4] + 12
                place(ld, (pluck(NOTE(n), s16 * 1.5, .1) if style == 'soft' else sq(NOTE(n), s16 * .9, 2500, .06)) * dec(int(s16 * (1.5 if style == 'soft' else .9) * SR), 3), at(b, s))
        elif style in ('afro', 'house', 'disco', 'garage'):
            for i in range(8):
                if mpat[i]: place(ld, (marimba if style == 'afro' else pluck)(NOTE(tones[motif[i]] + 12), s16 * 1.8, .14), at(b, i * 2))
        elif style in ('luxe', 'trap', 'cinematic'):
            for i in range(0, 8, 2):
                if mpat[i] and not intro: place(ld, bell(NOTE(tones[motif[i]] + 24), beat * 1.5, .12), at(b, i * 2))
        elif style == 'lofi':
            for i in range(0, 8, 3):
                place(ld, pluck(NOTE(tones[motif[i]] + 12), s16 * 3, .1, .5), at(b, i * 2))
        if style in ('house', 'disco', 'garage', 'synthwave', 'trap'):
            for q in range(4):
                s0 = int((b * bar + q * beat) * SR); n = int(beat * SR); pump[s0:s0 + n] = 1 - .45 * np.exp(-np.linspace(0, 6, n))
    pump[pump == 0] = 1
    if style == 'cinematic':  # riser into bar 2
        r = A.riser(2 * bar); place(ky, r * .3, 0)
    mix = dr * .85 + bs * pump + reverb(ky, 1.8, .3) * pump + reverb(ld, 1.2, .25) * .9
    if style == 'lofi':
        mix = lp(mix, 5000) + hp(rng.standard_normal(L), 3000) * .006 * (rng.random(L) > .9997).astype(float) * 30
    mix = np.tanh(mix * 1.25) * .9
    fade = int(SR * 1.0); mix[-fade:] *= np.linspace(1, 0, fade); mix[:int(SR * .03)] *= np.linspace(0, 1, int(SR * .03))
    R = reverb(mix, .25, .06)
    return norm(np.stack([mix, R], 1), .89), bpm, mode

def export(name, x):
    os.makedirs(os.path.join(HERE, 'music'), exist_ok=True)
    w = os.path.join(HERE, 'music', name + '.wav'); wavfile.write(w, SR, (np.clip(x, -1, 1) * 32767).astype(np.int16))
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', w, '-af', 'loudnorm=I=-14:TP=-1.5:LRA=11', '-ar', '48000', '-b:a', '256k', w[:-4] + '.mp3'], check=True)
    os.remove(w)

# ---------- SFX variants (each base sound gets 3-4 distinct versions + new story sounds)
def sfx_pack():
    out = {}
    out.update({f'whoosh--v{i}': A.whoosh(d, lo, hi) for i, (d, lo, hi) in enumerate([(.45, 400, 7000), (.7, 200, 5000), (.35, 800, 9000)], 1)})
    out.update({f'swoosh-reverse--v{i}': A.whoosh(d, lo, hi, rev=True) for i, (d, lo, hi) in enumerate([(.65, 300, 6000), (.4, 600, 8000)], 1)})
    def popv(f0, f1, dk):
        t = t_(.2); f = f0 * np.exp(-t * dk) + f1; return norm(np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 24), .85)
    out.update({'pop--v1': popv(1300, 250, 34), 'pop--v2': popv(600, 140, 22), 'pop--v3': popv(1800, 400, 45)})
    def chimev(notes, rv):
        y = np.zeros(int(SR * 1.7))
        for k, f in enumerate(notes):
            tt = t_(1.7 - k * .07); s = int(k * .07 * SR); y[s:s + len(tt)] += (np.sin(2 * np.pi * f * tt) + .4 * np.sin(2 * np.pi * f * 2.76 * tt)) * np.exp(-tt * 3.5) * .5
        return norm(reverb(y, rv, .35), .7)
    out.update({'chime--v1': chimev([1319, 1760, 2093, 2637], 1.6), 'chime--v2': chimev([2093, 1568, 1319], 2.2), 'chime--v3': chimev([1175, 1480, 1760, 2349, 2960], 1.8)})
    def clickv(f, d): t = t_(.05); return norm(np.sin(2 * np.pi * f * t) * np.exp(-t * d), .7)
    out.update({'click--v1': clickv(1800, 140), 'click--v2': clickv(3200, 180)})
    def boomv(f0, f1, d):
        t = t_(1.0); f = f0 * np.exp(-t * 4) + f1; return norm(reverb(np.tanh(1.6 * np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * d)), 1.0, .15), .9)
    out.update({'boom-slam--v1': boomv(70, 34, 2.6), 'boom-slam--v2': boomv(120, 50, 4.5)})
    out.update({'riser--v1': A.riser(1.2), 'riser--v2': A.riser(2.0)})
    out['shimmer--v1'] = A.shimmer(); out['shimmer--v2'] = A.shimmer()
    # new story sounds
    t = t_(.5); out['camera-shutter'] = norm(np.concatenate([hp(rng.standard_normal(int(.03 * SR)), 2000) * np.exp(-np.linspace(0, 8, int(.03 * SR))), np.zeros(int(.06 * SR)),
        bp(rng.standard_normal(int(.05 * SR)), 1500, 6000) * np.exp(-np.linspace(0, 6, int(.05 * SR)))]), .7)
    n = int(SR * .9); out['paper-rustle'] = norm(bp(rng.standard_normal(n), 2000, 9000) * (np.abs(np.sin(np.linspace(0, 23, n))) ** 3) * np.sin(np.pi * np.linspace(0, 1, n)), .5)
    n = int(SR * 2.2); w = lp(rng.standard_normal(n), 900); out['wind'] = norm(w * (.6 + .4 * np.sin(np.linspace(0, 6, n))) * np.sin(np.pi * np.linspace(0, 1, n)) ** 1.5, .5)
    out['bell-hit'] = norm(reverb(bell(1568, 2.0, 1), 2.0, .35), .7)
    tt = t_(.4); out['pluck-up'] = norm(np.concatenate([pluck(NOTE(n), .12, 1) for n in (72, 76, 79, 84)]), .7)
    tt = t_(.9); out['bass-hit'] = norm(np.tanh(2 * np.sin(2 * np.pi * np.cumsum(60 * np.exp(-tt * 3) + 35) / SR) * np.exp(-tt * 4)), .85)
    out['snap'] = norm(snap(1), .75)
    tt = t_(1.2); out['sparkle-sweep'] = norm(reverb(sum(np.sin(2 * np.pi * f * tt) * np.exp(-((tt - k * .07) * 30) ** 2) for k, f in enumerate(np.geomspace(1500, 6000, 14))), 1.6, .4), .6)
    for k, x in out.items(): A.save(k, x, 'sfx')
    for f in os.listdir(os.path.join(HERE, 'sfx')):
        if f.endswith('.mp3'): os.remove(os.path.join(HERE, 'sfx', f))

